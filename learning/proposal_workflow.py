#!/usr/bin/env python3
"""
Proposal Workflow - Continuous Improvement Proposal System

Manages the full lifecycle of improvement proposals generated by the
Learning Engine:
    Draft → Review → Approve → Implement → Verify → Close

Each proposal originates from a detected Pattern or post-mortem
analysis and is tracked through constitutional governance (Governor
approval required per Constitution Article V).
"""

import time
import json
import hashlib
from dataclasses import dataclass, field, asdict
from datetime import datetime
from enum import Enum
from pathlib import Path
from typing import Dict, Any, Optional, List, Callable


class ProposalStatus(Enum):
    DRAFT = "draft"
    UNDER_REVIEW = "under_review"
    APPROVED = "approved"
    REJECTED = "rejected"
    IMPLEMENTING = "implementing"
    VERIFYING = "verifying"
    CLOSED = "closed"
    ESCALATED = "escalated"


class ProposalPriority(Enum):
    LOW = "low"
    MEDIUM = "medium"
    HIGH = "high"
    CRITICAL = "critical"


class ProposalType(Enum):
    SKILL_UPDATE = "skill_update"
    PROCESS_CHANGE = "process_change"
    TOOL_INTEGRATION = "tool_integration"
    CONSTITUTION_AMENDMENT = "constitution_amendment"
    MEMORY_ARCHIVAL = "memory_archival"
    AGENT_ADJUSTMENT = "agent_adjustment"
    QA_RUBRIC_CHANGE = "qa_rubric_change"
    CUSTOM = "custom"


@dataclass
class Proposal:
    """A formal improvement proposal."""
    proposal_id: str
    title: str
    type: ProposalType
    description: str
    rationale: str
    priority: ProposalPriority
    status: ProposalStatus = ProposalStatus.DRAFT
    created_by: str = "learning_engine@vjsos-ai"
    created_at: str = field(default_factory=lambda: datetime.utcnow().isoformat() + "Z")
    updated_at: str = field(default_factory=lambda: datetime.utcnow().isoformat() + "Z")
    pattern_id: Optional[str] = None
    affected_components: List[str] = field(default_factory=list)
    estimated_impact: Dict[str, Any] = field(default_factory=dict)
    implementation_plan: Dict[str, Any] = field(default_factory=dict)
    verification_criteria: Dict[str, Any] = field(default_factory=dict)
    governor_decision: Optional[str] = None
    decision_rationale: Optional[str] = None
    approved_by: Optional[str] = None
    approved_at: Optional[str] = None
    implemented_at: Optional[str] = None
    verified_at: Optional[str] = None
    tags: List[str] = field(default_factory=list)

    def to_dict(self) -> Dict[str, Any]:
        data = asdict(self)
        data["type"] = self.type.value
        data["priority"] = self.priority.value
        data["status"] = self.status.value
        return data

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "Proposal":
        data = dict(data)
        data["type"] = ProposalType(data["type"])
        data["priority"] = ProposalPriority(data["priority"])
        data["status"] = ProposalStatus(data["status"])
        return cls(**data)


class ProposalWorkflow:
    """Orchestrates the proposal lifecycle with Governor integration."""

    def __init__(self, proposals_dir: str = "proposals"):
        self.workflow_id = "proposal-workflow@vjsos-ai"
        self.proposals_dir = Path(proposals_dir)
        self.proposals_dir.mkdir(parents=True, exist_ok=True)
        self.proposals: Dict[str, Proposal] = {}
        self.review_callbacks: List[Callable[[Proposal], None]] = []
        self.approval_callbacks: List[Callable[[Proposal], bool]] = []
        self._load_proposals()

    def _load_proposals(self):
        """Load existing proposals from disk."""
        for path in self.proposals_dir.glob("*.json"):
            try:
                with open(path) as f:
                    data = json.load(f)
                proposal = Proposal.from_dict(data)
                self.proposals[proposal.proposal_id] = proposal
            except Exception:
                pass

    def _save_proposal(self, proposal: Proposal):
        """Persist a single proposal to disk."""
        path = self.proposals_dir / f"{proposal.proposal_id}.json"
        with open(path, "w") as f:
            json.dump(proposal.to_dict(), f, indent=2)

    # ────────────── Lifecycle transitions ──────────────

    def create(self,
               title: str,
               proposal_type: ProposalType,
               description: str,
               rationale: str,
               priority: ProposalPriority = ProposalPriority.MEDIUM,
               pattern_id: Optional[str] = None,
               affected_components: Optional[List[str]] = None,
               estimated_impact: Optional[Dict[str, Any]] = None,
               implementation_plan: Optional[Dict[str, Any]] = None,
               verification_criteria: Optional[Dict[str, Any]] = None,
               created_by: str = "learning_engine@vjsos-ai",
               tags: Optional[List[str]] = None) -> Proposal:
        """Create a new proposal in DRAFT state."""
        proposal_id = f"prop_{int(time.time())}_{hashlib.md5(title.encode()).hexdigest()[:8]}"
        proposal = Proposal(
            proposal_id=proposal_id,
            title=title,
            type=proposal_type,
            description=description,
            rationale=rationale,
            priority=priority,
            status=ProposalStatus.DRAFT,
            created_by=created_by,
            pattern_id=pattern_id,
            affected_components=affected_components or [],
            estimated_impact=estimated_impact or {},
            implementation_plan=implementation_plan or {},
            verification_criteria=verification_criteria or {},
            tags=tags or []
        )
        self.proposals[proposal_id] = proposal
        self._save_proposal(proposal)
        return proposal

    def submit_for_review(self, proposal_id: str) -> Proposal:
        """Move DRAFT → UNDER_REVIEW and notify reviewers."""
        proposal = self.proposals[proposal_id]
        if proposal.status != ProposalStatus.DRAFT:
            raise ValueError(f"Cannot review proposal in status {proposal.status}")
        proposal.status = ProposalStatus.UNDER_REVIEW
        proposal.updated_at = datetime.utcnow().isoformat() + "Z"
        self._save_proposal(proposal)
        for cb in self.review_callbacks:
            cb(proposal)
        return proposal

    def review(self, proposal_id: str, approved: bool, reviewer: str,
               rationale: str = "") -> Proposal:
        """Record a review decision (Governor or delegated reviewer)."""
        proposal = self.proposals[proposal_id]
        if proposal.status != ProposalStatus.UNDER_REVIEW:
            raise ValueError("Proposal not under review")

        if approved:
            proposal.status = ProposalStatus.APPROVED
            proposal.approved_by = reviewer
            proposal.approved_at = datetime.utcnow().isoformat() + "Z"
            proposal.governor_decision = "approved"
            proposal.decision_rationale = rationale
            for cb in self.approval_callbacks:
                if not cb(proposal):
                    proposal.status = ProposalStatus.UNDER_REVIEW
                    break
        else:
            proposal.status = ProposalStatus.REJECTED
            proposal.governor_decision = "rejected"
            proposal.decision_rationale = rationale

        proposal.updated_at = datetime.utcnow().isoformat() + "Z"
        self._save_proposal(proposal)
        return proposal

    def start_implementation(self, proposal_id: str) -> Proposal:
        """Move APPROVED → IMPLEMENTING."""
        proposal = self.proposals[proposal_id]
        if proposal.status != ProposalStatus.APPROVED:
            raise ValueError("Only approved proposals can be implemented")
        proposal.status = ProposalStatus.IMPLEMENTING
        proposal.updated_at = datetime.utcnow().isoformat() + "Z"
        self._save_proposal(proposal)
        return proposal

    def mark_implemented(self, proposal_id: str, details: Dict[str, Any]) -> Proposal:
        """Move IMPLEMENTING → VERIFYING."""
        proposal = self.proposals[proposal_id]
        if proposal.status != ProposalStatus.IMPLEMENTING:
            raise ValueError("Proposal not in implementing state")
        proposal.status = ProposalStatus.VERIFYING
        proposal.implemented_at = datetime.utcnow().isoformat() + "Z"
        proposal.implementation_plan.update(details)
        proposal.updated_at = datetime.utcnow().isoformat() + "Z"
        self._save_proposal(proposal)
        return proposal

    def verify(self, proposal_id: str, verified: bool, verifier: str,
               evidence: Dict[str, Any] = None) -> Proposal:
        """Move VERIFYING → CLOSED (or back to IMPLEMENTING on failure)."""
        proposal = self.proposals[proposal_id]
        if proposal.status != ProposalStatus.VERIFYING:
            raise ValueError("Proposal not in verifying state")

        if verified:
            proposal.status = ProposalStatus.CLOSED
            proposal.verified_at = datetime.utcnow().isoformat() + "Z"
        else:
            proposal.status = ProposalStatus.IMPLEMENTING
            proposal.verification_criteria.update(evidence or {})

        proposal.updated_at = datetime.utcnow().isoformat() + "Z"
        self._save_proposal(proposal)
        return proposal

    def escalate(self, proposal_id: str, reason: str) -> Proposal:
        """Escalate a stuck or contentious proposal to Governor."""
        proposal = self.proposals[proposal_id]
        proposal.status = ProposalStatus.ESCALATED
        proposal.decision_rationale = f"ESCALATED: {reason}"
        proposal.updated_at = datetime.utcnow().isoformat() + "Z"
        self._save_proposal(proposal)
        return proposal

    # ────────────── Query helpers ──────────────

    def get(self, proposal_id: str) -> Optional[Proposal]:
        return self.proposals.get(proposal_id)

    def list_by_status(self, status: ProposalStatus) -> List[Proposal]:
        return [p for p in self.proposals.values() if p.status == status]

    def list_by_priority(self, priority: ProposalPriority) -> List[Proposal]:
        return [p for p in self.proposals.values() if p.priority == priority]

    def list_open(self) -> List[Proposal]:
        return [p for p in self.proposals.values()
                if p.status not in (ProposalStatus.CLOSED, ProposalStatus.REJECTED)]

    def get_stats(self) -> Dict[str, Any]:
        by_status = Counter(p.status.value for p in self.proposals.values())
        by_type = Counter(p.type.value for p in self.proposals.values())
        by_priority = Counter(p.priority.value for p in self.proposals.values())
        return {
            "total": len(self.proposals),
            "by_status": dict(by_status),
            "by_type": dict(by_type),
            "by_priority": dict(by_priority),
            "open": len(self.list_open()),
            "escalated": len(self.list_by_status(ProposalStatus.ESCALATED))
        }

    # ────────────── Extensibility ──────────────

    def on_review(self, callback: Callable[[Proposal], None]):
        """Register a callback invoked when a proposal enters review."""
        self.review_callbacks.append(callback)

    def on_approval(self, callback: Callable[[Proposal], bool]):
        """Register a callback invoked on approval; return False to veto."""
        self.approval_callbacks.append(callback)


def main():
    """Test the Proposal Workflow."""
    workflow = ProposalWorkflow("proposals_test")

    prop = workflow.create(
        title="Optimize Android build pipeline",
        proposal_type=ProposalType.PROCESS_CHANGE,
        description="Reduce build time by 40% via parallel Gradle tasks",
        rationale="Current average build duration 8min; target <5min",
        priority=ProposalPriority.HIGH,
        affected_components=["android-agent", "ci_cd_pipeline"],
        estimated_impact={"time_savings_pct": 40, "cost_reduction_usd_month": 120},
        tags=["performance", "engineering"]
    )
    print(f"Created: {prop.proposal_id}")

    workflow.submit_for_review(prop.proposal_id)
    print(f"Submitted: {prop.status}")

    workflow.review(prop.proposal_id, True, "governor@vjsos-ai", "High ROI, low risk")
    print(f"Approved: {prop.status}, by {prop.approved_by}")

    workflow.start_implementation(prop.proposal_id)
    workflow.mark_implemented(prop.proposal_id, {"commit": "abc123", "deployed": True})
    workflow.verify(prop.proposal_id, True, "qa_engine@vjsos-ai", {"build_time": 4.8})
    print(f"Closed: {prop.status}, verified at {prop.verified_at}")

    print(f"\nStats: {workflow.get_stats()}")


if __name__ == "__main__":
    main()